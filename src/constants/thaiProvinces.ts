/**
 * Returns available districts for a selected province.
 * Falls back to an empty list or a default city district.
 */
export function getDistrictsByProvince(province: string): string[] {
  if (!province) return PROVINCE_DISTRICTS_MAP['อุตรดิตถ์'];
  if (PROVINCE_DISTRICTS_MAP[province]) {
    return PROVINCE_DISTRICTS_MAP[province];
  }
  // Generic city district for other provinces
  return [`เมือง${province}`];
}
